#!/usr/bin/env python3
"""Pin model + effort in every agent file's frontmatter (escalation system).

Changes ONLY the `model:` and `effort:` lines of the frontmatter. The agent body is never touched.
Also writes an escalation twin `<name>-xhigh.md` (same body, effort: xhigh) that the agent-router
hook uses for retry step 2. Twins are generated files: never edit them by hand.

Usage:
  python3 tools/pin_agents.py <agents_dir>            # dry run: print the plan
  python3 tools/pin_agents.py <agents_dir> --apply    # back up, then write
  python3 tools/pin_agents.py <agents_dir> --verify   # check every agent is pinned and capped
"""
import re, sys, shutil, datetime
from pathlib import Path

# Film and judgement agents: Opus, high. Everything else: Sonnet, high.
OPUS = {
    "motion-director", "motion-designer", "video-editor",
    "creative-director", "script-director",
    "qa-reviewer",   # final check of a film before publishing (reviews a film)
}
# Name patterns that also count as "edits or reviews a film".
OPUS_PATTERNS = [r"film", r"edit(or|ing)?$", r"cut-?review", r"video-review", r"motion-"]
NOT_FILM = {"lesson-checker", "lesson-planner", "tutor-math", "language-tutor", "subtitle-agent"}
ALLOWED_MODELS = {"sonnet", "opus"}
ALLOWED_EFFORT = ["low", "medium", "high", "xhigh"]   # never "max" unless the owner asks
TWIN_SUFFIX = "-xhigh"
TWIN_MARK = "ESCALATION TWIN (generated by tools/pin_agents.py, used only by the agent-router hook on retry 2). Do not pick directly."

FM = re.compile(r"\A---\n(.*?)\n---\n", re.S)


def is_twin(p):
    return p.stem.endswith(TWIN_SUFFIX)


def choose(name):
    if name in NOT_FILM:
        return "sonnet", "high", "routine"
    if name in OPUS:
        return "opus", "high", "film/judgement (list)"
    if any(re.search(pt, name) for pt in OPUS_PATTERNS):
        return "opus", "high", "film/judgement (name rule)"
    return "sonnet", "high", "routine (default)"


def set_field(fm, key, value):
    """Set a top-level key. Replaces the key line AND its indented continuation lines (block scalars)."""
    lines, out, i, done = fm.split("\n"), [], 0, False
    while i < len(lines):
        ln = lines[i]
        if not done and re.match(rf"^{key}:", ln):
            out.append(f"{key}: {value}")
            i += 1
            while i < len(lines) and (lines[i].startswith((" ", "\t")) or lines[i] == ""):
                if lines[i] == "" and (i + 1 >= len(lines) or not lines[i + 1].startswith((" ", "\t"))):
                    break
                i += 1
            done = True
            continue
        out.append(ln)
        i += 1
    if not done:
        idx = next((k for k, l in enumerate(out) if l.startswith("model:")), None) if key == "effort" else None
        if idx is not None:
            out.insert(idx + 1, f"{key}: {value}")
        else:
            out.append(f"{key}: {value}")
    return "\n".join(out)


def get_field(fm, key):
    m = re.search(rf"^{key}:\s*(.*)$", fm, re.M)
    return m.group(1).strip().strip("'\"") if m else None


def plan(d):
    rows = []
    for p in sorted(d.glob("*.md")):
        if is_twin(p):
            continue
        txt = p.read_text(encoding="utf-8")
        m = FM.match(txt)
        if not m:
            rows.append((p, None, None, None, "NO FRONTMATTER: skipped, needs a look"))
            continue
        model, effort, why = choose(p.stem)
        rows.append((p, model, effort, (get_field(m.group(1), "model"), get_field(m.group(1), "effort")), why))
    return rows


def write(p, model, effort):
    txt = p.read_text(encoding="utf-8")
    m = FM.match(txt)
    fm = set_field(set_field(m.group(1), "model", model), "effort", effort)
    body = txt[m.end():]
    new = f"---\n{fm}\n---\n" + body
    assert new.endswith(body)                      # body untouched
    p.write_text(new, encoding="utf-8")
    # twin
    tfm = set_field(fm, "effort", "xhigh")
    name = get_field(tfm, "name") or p.stem
    tfm = set_field(tfm, "name", name + TWIN_SUFFIX)
    desc = get_field(tfm, "description") or ""
    if not desc.startswith("ESCALATION TWIN"):
        tfm = set_field(tfm, "description", f"\"{TWIN_MARK} Original: {name}.\"")
    (p.parent / f"{p.stem}{TWIN_SUFFIX}.md").write_text(f"---\n{tfm}\n---\n" + body, encoding="utf-8")


def verify(d):
    bad = []
    n = 0
    for p in sorted(d.glob("*.md")):
        m = FM.match(p.read_text(encoding="utf-8"))
        if not m:
            bad.append(f"{p.name}: no frontmatter")
            continue
        model, effort = get_field(m.group(1), "model"), get_field(m.group(1), "effort")
        if model not in ALLOWED_MODELS:
            bad.append(f"{p.name}: model {model!r} (must be sonnet or opus)")
        if effort not in ALLOWED_EFFORT:
            bad.append(f"{p.name}: effort {effort!r} (must be low..xhigh)")
        if not is_twin(p):
            n += 1
            if effort == "xhigh":
                bad.append(f"{p.name}: xhigh by default is not allowed")
            if not (p.parent / f"{p.stem}{TWIN_SUFFIX}.md").exists():
                bad.append(f"{p.name}: escalation twin missing")
    return n, bad


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    d = Path(sys.argv[1]).expanduser().resolve()
    mode = sys.argv[2] if len(sys.argv) > 2 else "--dry"
    if mode == "--verify":
        n, bad = verify(d)
        print(f"{n} agents checked in {d}")
        print("\n".join(bad) if bad else "VERIFY OK: every agent pinned (sonnet/opus, effort <= xhigh), every twin present")
        sys.exit(1 if bad else 0)
    rows = plan(d)
    print(f"{'agent':28} {'now':18} -> {'pinned':14} why")
    for p, model, effort, now, why in rows:
        nowtxt = f"{now[0]}/{now[1]}" if now else "-"
        print(f"{p.stem:28} {nowtxt:18} -> {(model or '-') + '/' + (effort or '-'):14} {why}")
    if mode == "--apply":
        bk = d.parent.parent / f"_backup_agents_{datetime.datetime.now():%Y%m%d-%H%M%S}"
        shutil.copytree(d, bk, symlinks=True)
        print(f"backup: {bk}")
        for p, model, effort, now, why in rows:
            if model:
                write(p, model, effort)
        n, bad = verify(d)
        print(f"pinned {n} agents")
        print("\n".join(bad) if bad else "VERIFY OK")


if __name__ == "__main__":
    main()
